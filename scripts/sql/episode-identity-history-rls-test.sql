CREATE FUNCTION public.test_protect_rated_episode_identity()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.episode_ratings WHERE episode_id = OLD.id) THEN
    IF TG_OP = 'DELETE' THEN
      RAISE EXCEPTION 'Rated episode identity is protected';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.podcast_key IS DISTINCT FROM OLD.podcast_key
       OR NEW.source IS DISTINCT FROM OLD.source THEN
      RAISE EXCEPTION 'Rated episode identity is protected';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END
$$;
