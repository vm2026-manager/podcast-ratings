import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { appleShowUrl, parseAppleFeed, parseHttpFeed } from "../supabase/functions/import-podcast-episodes/feed-syntax.mjs";

const __filename = fileURLToPath(import.meta.url);
const repoRoot = path.resolve(path.dirname(__filename), "..");
const podcastsPath = path.join(repoRoot, "data", "podcasts.json");
const feedConfigPath = path.join(
  repoRoot,
  "supabase",
  "functions",
  "import-podcast-episodes",
  "feed-config.ts"
);
const generatedStart = "  // BEGIN GENERATED SHEET FEEDS";
const generatedEnd = "  // END GENERATED SHEET FEEDS";

function normalizePodcastKey(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " og ")
    .replace(/[^a-z0-9\u00e6\u00f8\u00e5 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function toFeedKey(podcastId) {
  return normalizePodcastKey(podcastId).replace(/\s+/g, "_");
}

function getPodcastId(podcast) {
  return String(podcast?.["Podcast-ID"] ?? podcast?.["Podcast ID"] ?? podcast?.PodcastID ?? "").trim();
}

function getFeedUrl(podcast) {
  return String(podcast?.Feed ?? podcast?.feed ?? "").trim();
}

function getManualConfigKeys(configSource) {
  const beforeGenerated = configSource.split(generatedStart)[0];
  const keys = new Set();
  const podcastKeys = new Set();
  const entryPattern = /^\s{2}"([^"]+)"\s*:\s*\{([\s\S]*?)^\s{2}\},?$/gm;
  let match;

  while ((match = entryPattern.exec(beforeGenerated))) {
    keys.add(match[1]);
    const podcastKeyMatch = match[2].match(/podcast_key:\s*"([^"]+)"/);
    if (podcastKeyMatch) podcastKeys.add(normalizePodcastKey(podcastKeyMatch[1]));
  }

  return { keys, podcastKeys };
}

function escapeTsString(value) {
  return String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

export function buildSheetFeedEntries(podcasts, configSource, { identity = "podcast-id" } = {}) {
  const manual = getManualConfigKeys(configSource);
  const seenFeedKeys = new Set();
  const seenSources = new Set();
  const seenAppleShowIds = new Set();
  const generated = [];
  const invalid = [];
  const duplicates = [];
  const missingPodcastIds = [];
  let withFeed = 0;
  let existingPreserved = 0;

  for (const podcast of Array.isArray(podcasts) ? podcasts : []) {
    const title = String(podcast?.Titel ?? podcast?.title ?? "").trim();
    const rawFeedUrl = getFeedUrl(podcast);
    if (!rawFeedUrl) continue;
    withFeed += 1;

    const apple = parseAppleFeed(rawFeedUrl);
    const feedUrl = parseHttpFeed(rawFeedUrl);
    const podcastId = getPodcastId(podcast);
    if (identity === "podcast-id" && !podcastId) {
      missingPodcastIds.push({ title: title || "(mangler titel)", feed: rawFeedUrl });
      continue;
    }
    const identityValue = identity === "podcast-id" ? podcastId : title;
    const podcastKey = identity === "podcast-id" ? podcastId : normalizePodcastKey(title);
    const feedKey = apple ? `apple_${apple.appleShowId}` : toFeedKey(identityValue);
    if (!title || !podcastKey || !feedKey || (!feedUrl && !apple)) {
      invalid.push({ title: title || "(mangler titel)", feed: rawFeedUrl });
      continue;
    }

    // Manual entries own special formats (for example radio4_json) and win.
    if (manual.keys.has(feedKey) || manual.podcastKeys.has(podcastKey)) {
      existingPreserved += 1;
      continue;
    }

    const source = apple ? `apple_podcasts_${apple.appleShowId}` : `sheet_${feedKey}_rss`;
    if (seenFeedKeys.has(feedKey) || seenSources.has(source) || (apple && seenAppleShowIds.has(apple.appleShowId))) {
      duplicates.push({ title, feed: rawFeedUrl });
      continue;
    }

    seenFeedKeys.add(feedKey);
    seenSources.add(source);
    if (apple) seenAppleShowIds.add(apple.appleShowId);
    generated.push({
      feedKey,
      podcastKey,
      source,
      feedUrl: apple ? appleShowUrl(apple.appleShowId) : feedUrl,
      format: apple ? "apple_podcasts_html" : "rss",
      appleShowId: apple?.appleShowId || ""
    });
  }

  return {
    generated,
    summary: {
      totalPodcasts: Array.isArray(podcasts) ? podcasts.length : 0,
      podcastsWithFeed: withFeed,
      generatedFeedEntries: generated.length,
      existingFeedEntriesPreserved: manual.keys.size,
      sheetFeedsUsingExistingManualEntries: existingPreserved,
      skippedInvalidFeedUrls: invalid.length,
      duplicatesDetected: duplicates.length,
      missingPodcastIds: missingPodcastIds.length,
      invalid,
      missingPodcastIdRows: missingPodcastIds,
      duplicates
    }
  };
}

function renderGeneratedBlock(entries) {
  const lines = [
    generatedStart,
    "  // Generated by scripts/generate-feed-config-from-podcasts.mjs. Do not edit by hand."
  ];

  entries.forEach((entry) => {
    lines.push(
      `  "${escapeTsString(entry.feedKey)}": {`,
      `    podcast_key: "${escapeTsString(entry.podcastKey)}",`,
      `    source: "${escapeTsString(entry.source)}",`,
      `    feed_url: "${escapeTsString(entry.feedUrl)}",`,
      ...(entry.format === "apple_podcasts_html" ? [
        '    format: "apple_podcasts_html",',
        `    apple_show_id: "${escapeTsString(entry.appleShowId)}",`,
        "    enabled: false,"
      ] : []),
      "    generated_from_sheet: true",
      "  },"
    );
  });

  lines.push(generatedEnd);
  return lines.join("\n");
}

export async function generateFeedConfig({ write = true } = {}) {
  const [podcastsSource, configSource] = await Promise.all([
    readFile(podcastsPath, "utf8"),
    readFile(feedConfigPath, "utf8")
  ]);
  const parsed = JSON.parse(podcastsSource);
  const podcasts = Array.isArray(parsed) ? parsed : parsed?.rows;
  const { generated, summary } = buildSheetFeedEntries(podcasts, configSource);
  const block = renderGeneratedBlock(generated);
  const markerPattern = new RegExp(`${generatedStart}[\\s\\S]*?${generatedEnd}`);

  if (!markerPattern.test(configSource)) {
    throw new Error("Generated feed marker block is missing from feed-config.ts.");
  }

  const nextSource = configSource.replace(markerPattern, block);
  if (write && nextSource !== configSource) {
    await writeFile(feedConfigPath, nextSource, "utf8");
  }

  return { generated, summary, changed: nextSource !== configSource };
}

if (typeof process !== "undefined" && process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  const checkOnly = process.argv.includes("--check");
  generateFeedConfig({ write: !checkOnly })
    .then(({ summary, changed }) => {
      console.log(JSON.stringify({ ...summary, configChanged: changed, checkOnly }, null, 2));
    })
    .catch((error) => {
      console.error(error instanceof Error ? error.message : error);
      process.exitCode = 1;
    });
}
