
create table if not exists public.episode_identity_history (
  id bigint generated by default as identity primary key,
  episode_id uuid not null,
  changed_at timestamptz not null default now(),
  operation text not null,
  old_podcast_key text,
  new_podcast_key text,
  old_source text,
  new_source text,
  old_external_guid text,
  new_external_guid text,
  old_is_active boolean,
  new_is_active boolean,
  had_user_ratings boolean not null default false,
  had_manual_mapping boolean not null default false
);

revoke all on public.episode_identity_history from anon, authenticated;

create or replace function public.protect_episode_identity_and_ratings()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  has_ratings boolean;
  has_manual_mapping boolean;
  old_rateable boolean;
  new_rateable boolean;
begin
  select exists(select 1 from public.episode_ratings where episode_id = old.id)
    into has_ratings;
  select exists(select 1 from public.manual_catalogue_episode_map where episode_id = old.id and is_active = true)
    into has_manual_mapping;

  if tg_op = 'DELETE' then
    if has_ratings or has_manual_mapping then
      raise exception 'Protected episode % cannot be deleted: ratings or manual canonical mapping exist', old.id;
    end if;

    insert into public.episode_identity_history(
      episode_id, operation, old_podcast_key, old_source, old_external_guid,
      old_is_active, had_user_ratings, had_manual_mapping
    ) values (
      old.id, 'DELETE', old.podcast_key, old.source, old.external_guid,
      old.is_active, has_ratings, has_manual_mapping
    );
    return old;
  end if;

  if new.id is distinct from old.id
     or new.podcast_key is distinct from old.podcast_key
     or new.source is distinct from old.source
     or new.external_guid is distinct from old.external_guid then
    if has_ratings or has_manual_mapping then
      raise exception 'Protected episode % identity cannot change while ratings or manual canonical mapping exist', old.id;
    end if;
  end if;

  old_rateable := coalesce((old.metadata->>'rateable')::boolean, true);
  new_rateable := coalesce((new.metadata->>'rateable')::boolean, true);

  if (old.is_active is true and new.is_active is false)
     or (old_rateable is true and new_rateable is false) then
    if has_ratings or has_manual_mapping then
      raise exception 'Protected episode % cannot be hidden/deactivated while ratings or manual canonical mapping exist', old.id;
    end if;
  end if;

  if new.id is distinct from old.id
     or new.podcast_key is distinct from old.podcast_key
     or new.source is distinct from old.source
     or new.external_guid is distinct from old.external_guid
     or new.is_active is distinct from old.is_active then
    insert into public.episode_identity_history(
      episode_id, operation,
      old_podcast_key, new_podcast_key,
      old_source, new_source,
      old_external_guid, new_external_guid,
      old_is_active, new_is_active,
      had_user_ratings, had_manual_mapping
    ) values (
      old.id, 'UPDATE',
      old.podcast_key, new.podcast_key,
      old.source, new.source,
      old.external_guid, new.external_guid,
      old.is_active, new.is_active,
      has_ratings, has_manual_mapping
    );
  end if;

  return new;
end
$$;

drop trigger if exists trg_protect_episode_identity_and_ratings on public.podcast_episodes;
create trigger trg_protect_episode_identity_and_ratings
before update or delete on public.podcast_episodes
for each row
execute function public.protect_episode_identity_and_ratings();
