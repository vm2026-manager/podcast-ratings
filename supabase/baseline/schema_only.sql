CREATE OR REPLACE FUNCTION public.ensure_manual_catalogue_episode(p_podcast_key text, p_manual_episode_key text, p_episode_id uuid, p_title text, p_legacy_episode_id text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  existing_mapping public.manual_catalogue_episode_map%rowtype;
  candidate_ids uuid[];
  canonical_id uuid;
  legacy_ids text[] := '{}'::text[];
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  p_podcast_key := trim(coalesce(p_podcast_key, ''));
  p_manual_episode_key := trim(coalesce(p_manual_episode_key, ''));
  p_title := trim(coalesce(p_title, ''));

  if p_podcast_key = '' or p_manual_episode_key = '' or p_title = '' or p_episode_id is null then
    raise exception 'Invalid manual episode identity';
  end if;

  if p_manual_episode_key like 'manual-catalogue-v1:%' then
    if p_manual_episode_key <> 'manual-catalogue-v1:' || p_episode_id::text then
      raise exception 'Manual v1 key does not match episode UUID';
    end if;
  elsif p_manual_episode_key like 'manual-catalogue-v2:%' then
    if p_manual_episode_key not like 'manual-catalogue-v2:' || p_podcast_key || ':%' then
      raise exception 'Manual v2 key does not match podcast identity';
    end if;
  else
    raise exception 'Unsupported manual episode key';
  end if;

  select *
  into existing_mapping
  from public.manual_catalogue_episode_map
  where manual_episode_key = p_manual_episode_key
  for update;

  if found then
    if existing_mapping.podcast_key is distinct from p_podcast_key
       or existing_mapping.is_active is not true then
      raise exception 'Existing manual episode mapping conflicts with requested identity';
    end if;
    return existing_mapping.episode_id;
  end if;

  select array_agg(id order by id)
  into candidate_ids
  from public.podcast_episodes
  where podcast_key = p_podcast_key
    and is_active = true
    and public.episode_identity_fingerprint(title) = public.episode_identity_fingerprint(p_title);

  if coalesce(array_length(candidate_ids, 1), 0) > 1 then
    raise exception 'Ambiguous existing episode identity; manual episode was not linked';
  end if;

  canonical_id := case
    when coalesce(array_length(candidate_ids, 1), 0) = 1 then candidate_ids[1]
    else p_episode_id
  end;

  if canonical_id = p_episode_id then
    if exists (
      select 1
      from public.podcast_episodes
      where id = p_episode_id
        and (
          podcast_key is distinct from p_podcast_key
          or source is distinct from 'manual_catalogue_v1'
          or external_guid is distinct from 'manual_catalogue_v1:' || p_episode_id::text
        )
    ) then
      raise exception 'Manual episode UUID already belongs to another identity';
    end if;

    insert into public.podcast_episodes (
      id, podcast_key, source, external_guid, external_episode_id, title, is_active, metadata
    )
    values (
      p_episode_id,
      p_podcast_key,
      'manual_catalogue_v1',
      'manual_catalogue_v1:' || p_episode_id::text,
      p_manual_episode_key,
      p_title,
      true,
      jsonb_build_object(
        'manual_catalogue', true,
        'manual_episode_key', p_manual_episode_key,
        'identity_version', 'manual_catalogue_v1',
        'rateable', true
      )
    )
    on conflict (source, external_guid) do nothing;
  end if;

  if canonical_id <> p_episode_id then
    legacy_ids := array_append(legacy_ids, p_episode_id::text);
  end if;
  if nullif(trim(coalesce(p_legacy_episode_id, '')), '') is not null
     and not (trim(p_legacy_episode_id) = any(legacy_ids)) then
    legacy_ids := array_append(legacy_ids, trim(p_legacy_episode_id));
  end if;

  insert into public.manual_catalogue_episode_map (
    manual_episode_key, podcast_key, episode_id, canonical_source, legacy_episode_ids, title, is_active
  )
  values (
    p_manual_episode_key,
    p_podcast_key,
    canonical_id,
    'manual_catalogue_v1',
    legacy_ids,
    p_title,
    true
  );

  insert into public.episode_identity_audit (episode_id, action, new_identity, reason)
  values (
    canonical_id,
    'manual_episode_canonicalized',
    jsonb_build_object(
      'manual_episode_key', p_manual_episode_key,
      'podcast_key', p_podcast_key,
      'episode_id', canonical_id,
      'submitted_episode_id', p_episode_id,
      'title', p_title
    ),
    case when canonical_id = p_episode_id
      then 'created_manual_canonical_identity'
      else 'linked_manual_catalogue_to_existing_episode'
    end
  );

  return canonical_id;
end
$function$

CREATE OR REPLACE FUNCTION public.episode_identity_fingerprint(value text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO ''
AS $function$
  with normalized as (
    select lower(
      regexp_replace(
        regexp_replace(trim(coalesce(value, '')), '^teaser:\s*', '', 'i'),
        '\s+', ' ', 'g'
      )
    ) as title
  )
  select coalesce(
    nullif(substring(title from '([0-9]+:[0-9]+\s*-\s*.+)$'), ''),
    title
  )
  from normalized
$function$

CREATE OR REPLACE FUNCTION public.get_display_group_community_stats(p_display_group_ids text[])
 RETURNS TABLE(display_group_id text, average_rating numeric, rating_count integer)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
with requested_group_ids as (
  select distinct requested_ids.display_group_id
  from unnest(coalesce(p_display_group_ids, '{}'::text[])) as requested_ids(display_group_id)
  where requested_ids.display_group_id <> ''
),
requested_members as (
  select members.display_group_id, members.podcast_key
  from private.display_group_rating_members as members
  join requested_group_ids
    on requested_group_ids.display_group_id = members.display_group_id
),
direct_ratings as (
  select ratings.user_id, ratings.podcast_key, ratings.rating
  from public.user_ratings as ratings
  join (select distinct podcast_key from requested_members) as requested
    on requested.podcast_key = ratings.podcast_key
),
episode_user_ratings as (
  select episode_ratings.user_id, episodes.podcast_key, avg(episode_ratings.rating) as rating
  from public.episode_ratings as episode_ratings
  join public.podcast_episodes as episodes
    on episodes.id = episode_ratings.episode_id
  join (select distinct podcast_key from requested_members) as requested
    on requested.podcast_key = episodes.podcast_key
  where episodes.is_active = true
  group by episode_ratings.user_id, episodes.podcast_key
),
effective_user_ratings as (
  select
    coalesce(direct_ratings.user_id, episode_user_ratings.user_id) as user_id,
    coalesce(direct_ratings.podcast_key, episode_user_ratings.podcast_key) as podcast_key,
    coalesce(direct_ratings.rating, episode_user_ratings.rating) as rating
  from direct_ratings
  full join episode_user_ratings
    on episode_user_ratings.user_id = direct_ratings.user_id
   and episode_user_ratings.podcast_key = direct_ratings.podcast_key
),
per_user_group_ratings as (
  select
    requested_members.display_group_id,
    effective_user_ratings.user_id,
    avg(effective_user_ratings.rating) as user_average_rating
  from requested_members
  join effective_user_ratings
    on effective_user_ratings.podcast_key = requested_members.podcast_key
  group by requested_members.display_group_id, effective_user_ratings.user_id
)
select
  requested_group_ids.display_group_id,
  avg(per_user_group_ratings.user_average_rating) as average_rating,
  count(per_user_group_ratings.user_id)::integer as rating_count
from requested_group_ids
join (select distinct display_group_id from requested_members) as supported_groups
  on supported_groups.display_group_id = requested_group_ids.display_group_id
left join per_user_group_ratings
  on per_user_group_ratings.display_group_id = requested_group_ids.display_group_id
group by requested_group_ids.display_group_id;
$function$

