CREATE OR REPLACE FUNCTION public.mark_podcast_suggestion_response_seen(p_suggestion_id uuid)
 RETURNS TABLE(id uuid, user_seen_response_at timestamp with time zone)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth'
AS $function$
begin
  if auth.uid() is null then
    raise exception 'Authentication required'
      using errcode = '42501';
  end if;

  return query
  update public.podcast_suggestions as suggestion
  set user_seen_response_at = coalesce(suggestion.user_seen_response_at, now())
  where suggestion.id = p_suggestion_id
    and suggestion.suggested_by_user_id = auth.uid()
    and suggestion.reviewed_at is not null
  returning suggestion.id, suggestion.user_seen_response_at;

  if not found then
    raise exception 'Podcast suggestion response not found for current user'
      using errcode = 'P0002';
  end if;
end;
$function$

