CREATE OR REPLACE FUNCTION public.moderate_podcast_suggestion(p_suggestion_id uuid, p_status text, p_admin_note text DEFAULT NULL::text)
 RETURNS TABLE(id uuid, status text, reviewed_at timestamp with time zone, reviewed_by_user_id uuid, admin_note text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'auth'
AS $function$
begin
  if auth.uid() is null or not public.is_podcast_suggestions_admin() then
    raise exception 'Not authorized to moderate podcast suggestions'
      using errcode = '42501';
  end if;

  if p_status not in ('approved', 'rejected') then
    raise exception 'Invalid podcast suggestion moderation status'
      using errcode = '22023';
  end if;

  return query
  update public.podcast_suggestions as suggestion
  set
    status = p_status,
    reviewed_at = now(),
    reviewed_by_user_id = auth.uid(),
    admin_note = case
      when p_admin_note is null then suggestion.admin_note
      else nullif(btrim(p_admin_note), '')
    end,
    user_seen_response_at = null
  where suggestion.id = p_suggestion_id
  returning
    suggestion.id,
    suggestion.status,
    suggestion.reviewed_at,
    suggestion.reviewed_by_user_id,
    suggestion.admin_note;

  if not found then
    raise exception 'Podcast suggestion not found'
      using errcode = 'P0002';
  end if;
end;
$function$

