CREATE OR REPLACE VIEW public.episode_rating_public_stats AS
 SELECT episode_id,
    round(avg(rating), 1) AS average_rating,
    count(*)::integer AS rating_count
   FROM episode_ratings
  GROUP BY episode_id;;

CREATE OR REPLACE VIEW public.podcast_rating_combined_public_stats AS
 WITH direct_ratings AS (
         SELECT user_ratings.user_id,
            user_ratings.podcast_key,
            user_ratings.rating,
            COALESCE(user_ratings.updated_at, user_ratings.created_at) AS activity_at
           FROM user_ratings
        ), episode_user_ratings AS (
         SELECT er.user_id,
            pe.podcast_key,
            avg(er.rating) AS rating,
            max(COALESCE(er.updated_at, er.created_at)) AS activity_at,
            max(er.created_at) FILTER (WHERE er.rating >= 7::numeric) AS positive_activity_at
           FROM episode_ratings er
             JOIN podcast_episodes pe ON pe.id = er.episode_id
          WHERE pe.is_active = true
          GROUP BY er.user_id, pe.podcast_key
        ), effective_user_ratings AS (
         SELECT COALESCE(d.user_id, e.user_id) AS user_id,
            COALESCE(d.podcast_key, e.podcast_key) AS podcast_key,
            COALESCE(d.rating, e.rating) AS rating,
                CASE
                    WHEN d.user_id IS NULL THEN e.activity_at
                    ELSE GREATEST(COALESCE(d.activity_at, e.activity_at), e.positive_activity_at)
                END AS activity_at
           FROM direct_ratings d
             FULL JOIN episode_user_ratings e ON e.user_id = d.user_id AND e.podcast_key = d.podcast_key
        )
 SELECT podcast_key,
    avg(rating) AS average_rating,
    count(*)::integer AS rating_count,
    count(*) FILTER (WHERE activity_at >= (now() - '7 days'::interval))::integer AS recent_users_7d,
    count(*) FILTER (WHERE activity_at >= (now() - '30 days'::interval))::integer AS recent_users_30d,
    count(*) FILTER (WHERE activity_at >= (now() - '90 days'::interval))::integer AS recent_users_90d,
    count(*) FILTER (WHERE activity_at >= (now() - '7 days'::interval))::numeric + 0.35 * count(*) FILTER (WHERE activity_at >= (now() - '30 days'::interval) AND activity_at < (now() - '7 days'::interval))::numeric + 0.10 * count(*) FILTER (WHERE activity_at >= (now() - '90 days'::interval) AND activity_at < (now() - '30 days'::interval))::numeric AS momentum_score
   FROM effective_user_ratings
  GROUP BY podcast_key;;

CREATE OR REPLACE VIEW public.rating_public_stats AS
 SELECT podcast_key,
    round(avg(rating), 1) AS average_rating,
    count(*)::integer AS rating_count
   FROM user_ratings
  GROUP BY podcast_key;;

